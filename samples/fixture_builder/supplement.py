def enrich(file_id, pages):
    pages = [list(page) for page in pages]
    for index, paragraphs in EXTRAS.get(file_id, {}).items():
        # COA page zero must retain its natural table break. Put extra notes after the continuation.
        if file_id.startswith('COA') and index == 0:
            position = next(i for i,block in enumerate(pages[index]) if block[0]=='table') + 1
            pages[index][position:position] = [('paragraph', text) for text in paragraphs]
        else:
            pages[index].extend(('paragraph', text) for text in paragraphs)
    return pages
